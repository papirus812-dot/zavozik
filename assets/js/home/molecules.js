  // Брутто-формула по Хиллу (C, H, дальше по алфавиту); у ионов — заряд
  function formula(mol) {
    const n = {};
    const order = mol.a.map(() => 0);
    for (const [a, b, o] of mol.b) { order[a] += o; order[b] += o; }
    let charge = 0;
    mol.a.forEach(([, , el, chg, h], i) => {
      n[el] = (n[el] || 0) + 1;
      const hh = el === 'C' ? Math.max(0, 4 - order[i] - Math.abs(chg)) : h;
      if (hh) n.H = (n.H || 0) + hh;
      charge += chg;
    });
    const keys = n.C ? ['C', 'H', ...Object.keys(n).filter((k) => k !== 'C' && k !== 'H').sort()] : Object.keys(n).sort();
    let s = keys.filter((k) => n[k]).map((k) => k + (n[k] > 1 ? sub(n[k]) : '')).join('');
    if (charge) s += (Math.abs(charge) > 1 ? String(Math.abs(charge)).split('').map((d) => SUP[d]).join('') : '') + (charge > 0 ? '⁺' : '⁻');
    return s;
  }
