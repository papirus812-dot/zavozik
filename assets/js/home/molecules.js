  // Структурная формула: связи (двойные — второй линией внутрь кольца или по центру, клинья),
  // подписи гетероатомов с водородами и зарядами. Возвращает SVG и рамку.
  function drawMol(mol, cx, cy, BL) {
    const at = mol.a.map(([x, y, el, chg, h]) => ({ x: cx + x * BL, y: cy + y * BL, el, chg, h }));
    const nb = at.map(() => []);
    for (const [a, b] of mol.b) { nb[a].push(b); nb[b].push(a); }
    const dbl = at.map(() => 0);
    for (const [a, b, o] of mol.b) if (o === 2) { dbl[a]++; dbl[b]++; }
    const labeled = at.map((t, i) => t.el !== 'C' || nb[i].length === 0 || dbl[i] === 2);
    const lw = r1(BL * 0.085);
    const fs = r1(BL * 0.62);
    const trim = BL * 0.34;
    let out = '';
    const line = (x1, y1, x2, y2, extra = '') => `<line x1="${r1(x1)}" y1="${r1(y1)}" x2="${r1(x2)}" y2="${r1(y2)}"${extra}/>`;

    for (const [a, b, o, st] of mol.b) {
      const A = at[a], B = at[b];
      let dx = B.x - A.x, dy = B.y - A.y;
      const L = Math.hypot(dx, dy);
      dx /= L; dy /= L;
      const ta = labeled[a] ? trim : 0, tb = labeled[b] ? trim : 0;
      const x1 = A.x + dx * ta, y1 = A.y + dy * ta, x2 = B.x - dx * tb, y2 = B.y - dy * tb;
      const nx = -dy, ny = dx;
      if (st === 1 || st === 6) {
        const w = BL * 0.13;
        if (st === 1) {
          out += `<polygon points="${r1(x1)},${r1(y1)} ${r1(x2 + nx * w)},${r1(y2 + ny * w)} ${r1(x2 - nx * w)},${r1(y2 - ny * w)}" fill="${INK}" stroke="none"/>`;
        } else {
          const k = 6;
          for (let i = 1; i <= k; i++) {
            const t = i / k, px = x1 + (x2 - x1) * t, py = y1 + (y2 - y1) * t, hw = w * t;
            out += line(px - nx * hw, py - ny * hw, px + nx * hw, py + ny * hw);
          }
        }
        continue;
      }
      if (o === 1) {
        out += line(x1, y1, x2, y2);
        continue;
      }
      // двойная: с какой стороны больше соседей — туда вторая линия (внутрь кольца)
      let side = 0;
      for (const k of nb[a]) if (k !== b) side += Math.sign((at[k].x - A.x) * nx + (at[k].y - A.y) * ny);
      for (const k of nb[b]) if (k !== a) side += Math.sign((at[k].x - A.x) * nx + (at[k].y - A.y) * ny);
      const off = BL * 0.19;
      if (side === 0 || labeled[a] || labeled[b]) {
        const h = off / 2;
        out += line(x1 + nx * h, y1 + ny * h, x2 + nx * h, y2 + ny * h) + line(x1 - nx * h, y1 - ny * h, x2 - nx * h, y2 - ny * h);
      } else {
        const s = Math.sign(side), sh = BL * 0.14;
        out += line(x1, y1, x2, y2);
        out += line(x1 + dx * sh + nx * off * s, y1 + dy * sh + ny * off * s, x2 - dx * sh + nx * off * s, y2 - dy * sh + ny * off * s);
      }
    }
    // подписи атомов
    let labels = '';
    at.forEach((t, i) => {
      if (!labeled[i]) return;
      const color = EL[t.el] || INK;
      let mx = 0;
      for (const k of nb[i]) mx += at[k].x - t.x;
      const hLeft = nb[i].length > 0 && mx > 0.2;            // связи уходят вправо — водород слева
      const hs = t.h ? 'H' + (t.h > 1 ? sub(t.h) : '') : '';
      const chg = t.chg ? (Math.abs(t.chg) > 1 ? SUP[Math.abs(t.chg)] : '') + (t.chg > 0 ? '⁺' : '⁻') : '';
      const y = r1(t.y + fs * 0.36);
      if (!hs) {
        labels += `<text x="${r1(t.x)}" y="${y}" fill="${color}" text-anchor="middle">${t.el}${chg ? `<tspan font-size="${r1(fs * 0.72)}" dy="${r1(-fs * 0.4)}">${chg}</tspan>` : ''}</text>`;
      } else if (hLeft) {
        labels += `<text x="${r1(t.x + fs * 0.36)}" y="${y}" fill="${color}" text-anchor="end">${hs}${t.el}${chg}</text>`;
      } else {
        labels += `<text x="${r1(t.x - fs * 0.36)}" y="${y}" fill="${color}" text-anchor="start">${t.el}${hs}${chg}</text>`;
      }
    });
    const xs = at.map((t) => t.x), ys = at.map((t) => t.y);
    const pad = fs * 0.8;
    return {
      svg: `<g stroke="${INK}" stroke-width="${lw}" stroke-linecap="round" fill="none">${out}</g><g class="mol__atoms" font-size="${fs}">${labels}</g>`,
      box: [Math.min(...xs) - pad, Math.min(...ys) - pad, Math.max(...xs) + pad, Math.max(...ys) + pad],
    };
  }

